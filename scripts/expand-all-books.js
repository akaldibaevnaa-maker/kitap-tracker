// 2. Update SQLite data/kitaptracker.db
try {
  const db = new DatabaseSync('data/kitaptracker.db');
  Object.keys(ALL_EXPANDED).forEach(idStr => {
    const bookId = Number(idStr);
    const chs = ALL_EXPANDED[bookId];
    db.prepare('DELETE FROM chapters WHERE book_id = ?').run(bookId);
    chs.forEach((c, idx) => {
      db.prepare(`
        INSERT INTO chapters (book_id, idx, title, body, page_start, page_end)
        VALUES (?, ?, ?, ?, ?, ?)
      `).run(bookId, c.idx || (idx + 1), c.title, c.body, c.page_start, c.page_end);
    });
  });
  console.log('Successfully updated data/kitaptracker.db SQLite database!');
} catch (e) {
  console.error('Error syncing SQLite:', e);
}

